CREATE OR REPLACE FUNCTION private.household_join_rate_limit (
  p_user_id   uuid,
  p_succeeded boolean DEFAULT NULL::boolean
)
  RETURNS timestamp WITH time zone
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_now timestamptz := now();
  v_failed_attempts integer;
  v_window_started_at timestamptz;
  v_locked_until timestamptz;
begin
  insert into public.household_join_rate_limits (user_id)
  values (p_user_id)
  on conflict (user_id) do nothing;

  select failed_attempts, window_started_at, locked_until
  into v_failed_attempts, v_window_started_at, v_locked_until
  from public.household_join_rate_limits
  where user_id = p_user_id
  for update;

  if p_succeeded is null then
    if (v_locked_until is not null and v_locked_until <= v_now)
      or v_window_started_at <= v_now - interval '10 minutes'
    then
      update public.household_join_rate_limits
      set failed_attempts = 0,
          window_started_at = v_now,
          locked_until = null
      where user_id = p_user_id;
      return null;
    end if;

    if v_locked_until > v_now then
      return v_locked_until;
    end if;

    return null;
  end if;

  if p_succeeded then
    update public.household_join_rate_limits
    set failed_attempts = 0,
        window_started_at = v_now,
        locked_until = null
    where user_id = p_user_id;
    return null;
  end if;

  update public.household_join_rate_limits
  set failed_attempts = failed_attempts + 1,
      locked_until = case
        when failed_attempts + 1 >= 10 then v_now + interval '10 minutes'
        else null
      end
  where user_id = p_user_id
  returning locked_until into v_locked_until;

  return v_locked_until;
end;
$function$;

CREATE OR REPLACE FUNCTION private.record_household_recipe_activity (
  p_household_id uuid,
  p_recipe_id    uuid,
  p_recipe_title text,
  p_action       text
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_user_id uuid := auth.uid();
  v_actor_display_name text;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  if p_action not in ('added', 'edited', 'unshared') then
    raise exception 'invalid household recipe activity' using errcode = '22023';
  end if;

  if not exists (
    select 1
    from public.recipes recipes
    where recipes.id = p_recipe_id
      and recipes.owner_user_id = v_user_id
  ) then
    raise exception 'recipe ownership required' using errcode = '42501';
  end if;

  select coalesce(
    nullif(btrim(to_jsonb(profiles) ->> 'display_name'), ''),
    nullif(btrim(to_jsonb(profiles) ->> 'full_name'), ''),
    nullif(btrim(to_jsonb(profiles) ->> 'name'), ''),
    nullif(btrim(users.raw_user_meta_data ->> 'full_name'), ''),
    nullif(btrim(users.raw_user_meta_data ->> 'name'), ''),
    case
      when members.role = 'owner' then 'Household owner'
      else 'Household member'
    end
  )
  into v_actor_display_name
  from public.household_members members
  left join public.profiles profiles on profiles.id = members.user_id
  left join auth.users users on users.id = members.user_id
  where members.household_id = p_household_id
    and members.user_id = v_user_id;

  if not found then
    raise exception 'household membership required' using errcode = '42501';
  end if;

  insert into public.household_recipe_activities (
    household_id,
    actor_user_id,
    actor_display_name,
    action,
    recipe_id,
    recipe_title
  ) values (
    p_household_id,
    v_user_id,
    v_actor_display_name,
    p_action,
    p_recipe_id,
    coalesce(nullif(btrim(p_recipe_title), ''), 'Untitled recipe')
  );
end;
$function$;

CREATE OR REPLACE FUNCTION private.record_shared_recipe_edit()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_household_id uuid;
begin
  for v_household_id in
    select shares.household_id
    from public.household_recipe_shares shares
    where shares.recipe_id = new.id
  loop
    perform private.record_household_recipe_activity(
      v_household_id,
      new.id,
      new.title,
      'edited'
    );
  end loop;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.create_personal_cookbook (
  p_title      text,
  p_recipe_ids uuid[] DEFAULT '{}'::uuid[]
)
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_user_id uuid := auth.uid();
  v_cookbook_id uuid;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  if p_title is null or char_length(btrim(p_title)) not between 1 and 100 then
    raise exception 'invalid cookbook title' using errcode = '22023';
  end if;

  if exists (
    select 1
    from unnest(coalesce(p_recipe_ids, '{}'::uuid[])) selected(recipe_id)
    where selected.recipe_id is null
      or not exists (
        select 1
        from public.recipes recipes
        where recipes.id = selected.recipe_id
          and recipes.owner_user_id = v_user_id
      )
  ) then
    return jsonb_build_object('status', 'INVALID_RECIPE');
  end if;

  insert into public.cookbooks (owner_user_id, title)
  values (v_user_id, btrim(p_title))
  returning id into v_cookbook_id;

  insert into public.cookbook_recipes (cookbook_id, recipe_id)
  select v_cookbook_id, selected.recipe_id
  from (
    select distinct recipe_id
    from unnest(coalesce(p_recipe_ids, '{}'::uuid[])) recipe_ids(recipe_id)
  ) selected;

  return jsonb_build_object(
    'status', 'OK',
    'cookbook_id', v_cookbook_id
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.get_household_activity()
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_user_id uuid := auth.uid();
  v_household_id uuid;
  v_joined_at timestamptz;
  v_last_seen_activity_id bigint;
  v_member_count integer;
  v_latest_activity_id bigint;
  v_unread_count integer;
  v_activities jsonb;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  select members.household_id, members.joined_at, members.last_seen_activity_id
  into v_household_id, v_joined_at, v_last_seen_activity_id
  from public.household_members members
  where members.user_id = v_user_id;

  if not found then
    return jsonb_build_object('status', 'NO_HOUSEHOLD');
  end if;

  select count(*)::integer
  into v_member_count
  from public.household_members members
  where members.household_id = v_household_id;

  select max(activities.id)
  into v_latest_activity_id
  from public.household_recipe_activities activities
  where activities.household_id = v_household_id
    and activities.created_at >= v_joined_at;

  select count(*)::integer
  into v_unread_count
  from public.household_recipe_activities activities
  where activities.household_id = v_household_id
    and activities.created_at >= v_joined_at
    and activities.id > coalesce(v_last_seen_activity_id, 0)
    and activities.actor_user_id is distinct from v_user_id;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', visible.id,
        'actor_user_id', visible.actor_user_id,
        'actor_display_name', visible.actor_display_name,
        'action', visible.action,
        'recipe_id', visible.readable_recipe_id,
        'recipe_title', visible.recipe_title,
        'created_at', visible.created_at
      )
      order by visible.id desc
    ),
    '[]'::jsonb
  )
  into v_activities
  from (
    select
      activities.id,
      activities.actor_user_id,
      activities.actor_display_name,
      activities.action,
      case
        when activities.action <> 'unshared' and shares.recipe_id is not null
          then activities.recipe_id
        else null
      end as readable_recipe_id,
      activities.recipe_title,
      activities.created_at
    from public.household_recipe_activities activities
    left join public.household_recipe_shares shares
      on shares.household_id = activities.household_id
      and shares.recipe_id = activities.recipe_id
    where activities.household_id = v_household_id
      and activities.created_at >= v_joined_at
    order by activities.id desc
    limit 50
  ) visible;

  return jsonb_build_object(
    'status', 'OK',
    'member_count', v_member_count,
    'unread_count', v_unread_count,
    'latest_activity_id', v_latest_activity_id,
    'activities', v_activities
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.get_household_settings()
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_user_id uuid := auth.uid();
  v_household_id uuid;
  v_household_name text;
  v_role text;
  v_members jsonb;
  v_code_expires_at timestamptz;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  select hm.household_id, h.name, hm.role
  into v_household_id, v_household_name, v_role
  from public.household_members hm
  join public.households h on h.id = hm.household_id
  where hm.user_id = v_user_id;

  if not found then
    return jsonb_build_object('status', 'NO_HOUSEHOLD');
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'user_id', members.user_id,
        'display_name', coalesce(
          nullif(btrim(to_jsonb(profiles) ->> 'display_name'), ''),
          nullif(btrim(to_jsonb(profiles) ->> 'full_name'), ''),
          nullif(btrim(to_jsonb(profiles) ->> 'name'), ''),
          nullif(btrim(users.raw_user_meta_data ->> 'full_name'), ''),
          nullif(btrim(users.raw_user_meta_data ->> 'name'), ''),
          case
            when members.role = 'owner' then 'Household owner'
            else 'Household member'
          end
        ),
        'role', members.role
      )
      order by (members.role = 'owner') desc, members.joined_at, members.user_id
    ),
    '[]'::jsonb
  )
  into v_members
  from public.household_members members
  left join public.profiles profiles on profiles.id = members.user_id
  left join auth.users users on users.id = members.user_id
  where members.household_id = v_household_id;

  if v_role = 'owner' then
    select expires_at
    into v_code_expires_at
    from public.household_join_codes
    where household_id = v_household_id
      and expires_at > now();
  end if;

  return jsonb_build_object(
    'status', 'OK',
    'household_id', v_household_id,
    'household_name', v_household_name,
    'role', v_role,
    'member_count', jsonb_array_length(v_members),
    'members', v_members,
    'active_code_expires_at', v_code_expires_at
  );
end;
$function$;

