CREATE OR REPLACE FUNCTION public.preview_household_join_code (
  p_code_digest text
)
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_user_id uuid := auth.uid();
  v_existing_household_id uuid;
  v_existing_role text;
  v_locked_until timestamptz;
  v_household_id uuid;
  v_household_name text;
  v_owner_display_name text;
  v_member_count integer;
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  select household_id, role
  into v_existing_household_id, v_existing_role
  from public.household_members
  where user_id = v_user_id;

  if found then
    return jsonb_build_object(
      'status', 'ALREADY_MEMBER',
      'household_id', v_existing_household_id,
      'role', v_existing_role
    );
  end if;

  v_locked_until := private.household_join_rate_limit(v_user_id, null);
  if v_locked_until is not null then
    return jsonb_build_object(
      'status', 'RATE_LIMITED',
      'retry_after_seconds', greatest(
        1,
        ceil(extract(epoch from (v_locked_until - now())))::integer
      )
    );
  end if;

  if p_code_digest ~ '^[0-9a-f]{64}$' then
    select
      h.id,
      h.name,
      coalesce(
        nullif(to_jsonb(p) ->> 'display_name', ''),
        nullif(to_jsonb(p) ->> 'full_name', ''),
        nullif(to_jsonb(p) ->> 'name', ''),
        'Household owner'
      ),
      (
        select count(*)::integer
        from public.household_members members
        where members.household_id = h.id
      )
    into
      v_household_id,
      v_household_name,
      v_owner_display_name,
      v_member_count
    from public.household_join_codes c
    join public.households h on h.id = c.household_id
    left join public.profiles p on p.id = h.created_by
    where c.code_digest = p_code_digest
      and c.expires_at > now();
  end if;

  if v_household_id is null then
    perform private.household_join_rate_limit(v_user_id, false);
    return jsonb_build_object('status', 'INVALID_OR_EXPIRED');
  end if;

  perform private.household_join_rate_limit(v_user_id, true);

  return jsonb_build_object(
    'status', 'OK',
    'household_name', v_household_name,
    'owner_display_name', v_owner_display_name,
    'member_count', v_member_count
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.replace_household_join_code (
  p_code_digest text
)
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_user_id uuid := auth.uid();
  v_household_id uuid;
  v_expires_at timestamptz := now() + interval '10 minutes';
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  if p_code_digest !~ '^[0-9a-f]{64}$' then
    raise exception 'invalid code digest' using errcode = '22023';
  end if;

  select household_id
  into v_household_id
  from public.household_members
  where user_id = v_user_id
    and role = 'owner';

  if not found then
    return jsonb_build_object('status', 'FORBIDDEN');
  end if;

  insert into public.household_join_codes (
    household_id,
    code_digest,
    created_by,
    created_at,
    expires_at
  ) values (
    v_household_id,
    p_code_digest,
    v_user_id,
    now(),
    v_expires_at
  )
  on conflict (household_id) do update
  set code_digest = excluded.code_digest,
      created_by = excluded.created_by,
      created_at = excluded.created_at,
      expires_at = excluded.expires_at;

  return jsonb_build_object(
    'status', 'OK',
    'expires_at', v_expires_at
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.replace_personal_cookbook_recipes (
  p_cookbook_id uuid,
  p_recipe_ids  uuid[] DEFAULT '{}'::uuid[]
)
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  perform 1
  from public.cookbooks cookbooks
  where cookbooks.id = p_cookbook_id
    and cookbooks.owner_user_id = v_user_id
  for update;

  if not found then
    return jsonb_build_object('status', 'COOKBOOK_NOT_FOUND');
  end if;

  if exists (
    select 1
    from unnest(coalesce(p_recipe_ids, '{}'::uuid[])) selected(recipe_id)
    where selected.recipe_id is null
      or not exists (
        select 1
        from public.recipes recipes
        where recipes.id = selected.recipe_id
          and recipes.owner_user_id = v_user_id
      )
  ) then
    return jsonb_build_object('status', 'INVALID_RECIPE');
  end if;

  delete from public.cookbook_recipes cookbook_recipes
  where cookbook_recipes.cookbook_id = p_cookbook_id;

  insert into public.cookbook_recipes (cookbook_id, recipe_id)
  select p_cookbook_id, selected.recipe_id
  from (
    select distinct recipe_id
    from unnest(coalesce(p_recipe_ids, '{}'::uuid[])) recipe_ids(recipe_id)
  ) selected;

  return jsonb_build_object('status', 'OK');
end;
$function$;

